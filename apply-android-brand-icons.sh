#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RES="$ROOT/android/app/src/main/res"
ASSETS="$ROOT/brand-assets"
MANIFEST="$ROOT/android/app/src/main/AndroidManifest.xml"

if [ ! -d "$RES" ]; then
  echo "ERROR: Android project not found at $RES. Run npx cap add android first." >&2
  exit 1
fi
if [ ! -f "$MANIFEST" ]; then
  echo "ERROR: AndroidManifest.xml not found at $MANIFEST." >&2
  exit 1
fi

# Require all density-specific launcher assets instead of silently shipping a
# generated APK with missing icon resources.
for density in mdpi hdpi xhdpi xxhdpi xxxhdpi; do
  src="$ASSETS/android-mipmap/mipmap-$density"
  dst="$RES/mipmap-$density"
  for icon in ic_launcher.png ic_launcher_round.png; do
    if [ ! -s "$src/$icon" ]; then
      echo "ERROR: Required launcher asset missing: $src/$icon" >&2
      exit 1
    fi
  done
  mkdir -p "$dst"
  cp "$src/ic_launcher.png" "$dst/ic_launcher.png"
  cp "$src/ic_launcher_round.png" "$dst/ic_launcher_round.png"
done

mkdir -p "$RES/drawable-nodpi" "$RES/mipmap-anydpi-v26" "$RES/values"
if [ ! -s "$ASSETS/royal-hires-emblem-white.png" ]; then
  echo "ERROR: White emblem foreground asset is missing." >&2
  exit 1
fi
cp "$ASSETS/royal-hires-emblem-white.png" "$RES/drawable-nodpi/ic_launcher_foreground.png"

# Adaptive launcher icon: white emblem only, no wordmark, on emerald green.
cat > "$RES/mipmap-anydpi-v26/ic_launcher.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
XML
cat > "$RES/mipmap-anydpi-v26/ic_launcher_round.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
XML

COLORS="$RES/values/colors.xml"
if [ -f "$COLORS" ]; then
  if grep -q 'name="ic_launcher_background"' "$COLORS"; then
    sed -i 's|<color name="ic_launcher_background">[^<]*</color>|<color name="ic_launcher_background">#0B4D3B</color>|' "$COLORS"
  else
    sed -i 's|</resources>|    <color name="ic_launcher_background">#0B4D3B</color>\n</resources>|' "$COLORS"
  fi
else
  printf '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#0B4D3B</color>\n</resources>\n' > "$COLORS"
fi

# Explicitly bind both launcher icons in the generated native manifest. This
# prevents template differences from leaving the APK with the default icon.
if grep -q 'android:icon=' "$MANIFEST"; then
  sed -i 's|android:icon="[^"]*"|android:icon="@mipmap/ic_launcher"|' "$MANIFEST"
else
  sed -i 's|<application|<application android:icon="@mipmap/ic_launcher"|' "$MANIFEST"
fi
if grep -q 'android:roundIcon=' "$MANIFEST"; then
  sed -i 's|android:roundIcon="[^"]*"|android:roundIcon="@mipmap/ic_launcher_round"|' "$MANIFEST"
else
  sed -i 's|<application|<application android:roundIcon="@mipmap/ic_launcher_round"|' "$MANIFEST"
fi

# Remove the duplicate resource generated by some Capacitor templates.
rm -f "$RES/values/ic_launcher_background.xml"

test -s "$RES/mipmap-mdpi/ic_launcher.png"
test -s "$RES/mipmap-xxxhdpi/ic_launcher.png"
test -s "$RES/mipmap-anydpi-v26/ic_launcher.xml"
test -s "$RES/mipmap-anydpi-v26/ic_launcher_round.xml"
grep -q 'android:icon="@mipmap/ic_launcher"' "$MANIFEST"
grep -q 'android:roundIcon="@mipmap/ic_launcher_round"' "$MANIFEST"
echo "Royal Hires launcher branding applied and verified."
