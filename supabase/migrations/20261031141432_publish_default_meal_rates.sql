create table if not exists public.meal_rates (
  id bigint generated by default as identity primary key,
  breakfast numeric(10,2) not null default 130 check (breakfast >= 0),
  lunch numeric(10,2) not null default 250 check (lunch >= 0),
  dinner numeric(10,2) not null default 250 check (dinner >= 0),
  effective_from date not null default current_date unique,
  created_at timestamptz not null default now()
);
alter table public.meal_rates enable row level security;
grant select on public.meal_rates to authenticated;
drop policy if exists "authenticated users read meal rates" on public.meal_rates;
create policy "authenticated users read meal rates"
  on public.meal_rates for select to authenticated using (true);
insert into public.meal_rates (breakfast,lunch,dinner,effective_from)
values (130,250,250,current_date)
on conflict (effective_from) do nothing;